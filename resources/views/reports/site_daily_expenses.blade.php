@push('scripts')
    <script>
        $(document).ready(function () {
            // Period selector toggles custom date inputs
            $('#reportPeriodSelect').on('change', function () {
                if ($(this).val() === 'custom') {
                    $('#customStartDateCol, #customEndDateCol').slideDown(150);
                } else {
                    $('#customStartDateCol, #customEndDateCol').slideUp(150);
                }
            });

            // Table Client-Side Pagination
            let currentPage = 1;
            let perPage = parseInt($('#perPageSelect').val()) || 10;

            function updatePagination() {
                const rows = $('#expensesTableBody tr.expense-row');
                const totalCount = rows.length;
                const totalPages = Math.ceil(totalCount / perPage) || 1;

                if (currentPage > totalPages) {
                    currentPage = totalPages;
                }
                if (currentPage < 1) {
                    currentPage = 1;
                }

                rows.hide();

                if (totalCount === 0) {
                    $('#tablePaginationContainer').addClass('d-none');
                    $('#pageIndicator').text('Page 0 of 0');
                    return;
                } else {
                    $('#tablePaginationContainer').removeClass('d-none');
                }

                const startIndex = (currentPage - 1) * perPage;
                const endIndex = Math.min(startIndex + perPage, totalCount);

                let pageSum = 0;
                for (let i = startIndex; i < endIndex; i++) {
                    const r = $(rows[i]);
                    r.show();
                    r.find('.expense-row-num').text(i + 1);
                    pageSum += parseFloat(r.data('amount')) || 0;
                }

                $('#pageStart').text(startIndex + 1);
                $('#pageEnd').text(endIndex);
                $('#pageTotal').text(totalCount);
                $('#pageIndicator').text(`Page ${currentPage} of ${totalPages}`);
                $('#pageTotalAmount').text('₹' + pageSum.toLocaleString('en-IN', { minimumFractionDigits: 2, maximumFractionDigits: 2 }));

                renderPaginationButtons(totalPages, currentPage);
            }

            function renderPaginationButtons(totalPages, current) {
                const nav = $('#paginationNav');
                nav.empty();

                const prevDisabled = current === 1 ? 'disabled' : '';
                nav.append(`
                    <li class="page-item ${prevDisabled}">
                        <button class="page-link" type="button" data-page="${current - 1}" aria-label="Previous" title="Previous Page">
                            <i class="bi bi-chevron-left"></i>
</button>
                    </li>
                `);

                let pages = [];
                if (totalPages <= 7) {
                    for (let i = 1; i <= totalPages; i++) pages.push(i);
                } else {
                    pages.push(1);
                    if (current > 3) pages.push('...');
                    const start = Math.max(2, current - 1);
                    const end = Math.min(totalPages - 1, current + 1);
                    for (let i = start; i <= end; i++) {
                        if (!pages.includes(i)) pages.push(i);
                    }
                    if (current < totalPages - 2) pages.push('...');
                    if (!pages.includes(totalPages)) pages.push(totalPages);
                }

                pages.forEach(p => {
                    if (p === '...') {
                        nav.append(`<li class="page-item disabled"><span class="page-link border-0 bg-transparent">&hellip;</span></li>`);
                    } else {
                        const active = p === current ? 'active' : '';
                        nav.append(`
                            <li class="page-item ${active}">
                                <button class="page-link" type="button" data-page="${p}">${p}</button>
                            </li>
                        `);
                    }
                });

                const nextDisabled = current === totalPages ? 'disabled' : '';
                nav.append(`
                    <li class="page-item ${nextDisabled}">
                        <button class="page-link" type="button" data-page="${current + 1}" aria-label="Next" title="Next Page">
                            <i class="bi bi-chevron-right"></i>
</button>
                    </li>
                `);
            }

            $('#perPageSelect').on('change', function () {
                perPage = parseInt($(this).val()) || 10;
                currentPage = 1;
                updatePagination();
            });

            $(document).on('click', '#paginationNav .page-link', function (e) {
                e.preventDefault();
                const page = $(this).data('page');
                if (page && !$(this).parent().hasClass('disabled') && !$(this).parent().hasClass('active')) {
                    currentPage = parseInt(page);
                    updatePagination();
                }
            });

            // Initial pagination run
            updatePagination();
        });
    </script>
@endpush
